export function normalizeLocale (value) {
  const locale = String(value || '').toLocaleLowerCase()
  if (locale.startsWith('zh')) return 'zh'
  if (locale.startsWith('ja')) return 'ja'
  if (locale.startsWith('en')) return 'en'
  return null
}

export function detectLocale (languages = []) {
  for (const language of languages || []) {
    const locale = normalizeLocale(language)
    if (locale) return locale
  }
  return 'en'
}

function interpolate (template, values) {
  return template.replace(/\{(\w+)\}/g, (_, name) => (
    Object.hasOwn(values, name) ? String(values[name]) : `{${name}}`
  ))
}

export function localizedField (entity, locale, field) {
  return entity?.translations?.[locale]?.[field] || ''
}

export function displaySongTitle (song) {
  return originalSongTitle(song?.title, song?.language)
}

const VERIFIED_ORIGIN_SERVICES = new Set([
  'qqmusic',
  'netease',
  'apple-music',
  'local-files',
])

export function displaySongSubtitle (song, locale) {
  const imported = VERIFIED_ORIGIN_SERVICES.has(song?.source?.service)
  const structured = formatSongOrigin(
    song?.origin,
    normalizeLocale(locale),
    { requireVerified: imported },
  )
  if (structured) return structured
  const original = String(song?.subtitle || '')
  // Provider descriptions are often localized, stale, or copied from the
  // source novel/comic. Imported songs expose a structured origin only after
  // the direct audiovisual production and its native title are verified.
  if (imported && parseSongOrigin(original)) return ''
  return localizeSongOrigin(original, normalizeLocale(locale))
}

export function displayCollectionName (collection, locale) {
  return localizedField(collection, locale, 'name') || String(collection?.name || '')
}

export function displayCollectionDescription (collection, locale) {
  return localizedField(collection, locale, 'description') || String(collection?.description || '')
}

export default class I18n {
  constructor ({
    languages = typeof navigator === 'undefined'
      ? []
      : (navigator.languages || [navigator.language]),
    storage = undefined,
  } = {}) {
    if (storage === undefined) {
      try {
        storage = window.localStorage
      } catch {
        storage = null
      }
    }
    this.storage = storage
    this.listeners = new Set()
    let saved = null
    try {
      saved = normalizeLocale(this.storage?.getItem(LOCALE_STORAGE_KEY))
    } catch {}
    this.locale = saved || detectLocale(languages)
    this.updateDocumentLanguage()
  }

  t (key, values = {}) {
    const template = MESSAGES[this.locale]?.[key] ?? MESSAGES.en[key] ?? key
    return interpolate(template, values)
  }

  languageName () {
    return LOCALE_NAMES[this.locale]
  }

  setLocale (value) {
    const locale = normalizeLocale(value)
    if (!locale || locale === this.locale) return false
    this.locale = locale
    try {
      this.storage?.setItem(LOCALE_STORAGE_KEY, locale)
    } catch {}
    this.updateDocumentLanguage()
    for (const listener of this.listeners) listener(locale)
    return true
  }

  cycleLocale () {
    const index = SUPPORTED_LOCALES.indexOf(this.locale)
    this.setLocale(SUPPORTED_LOCALES[(index + 1) % SUPPORTED_LOCALES.length])
    return this.locale
  }

  subscribe (listener) {
    this.listeners.add(listener)
    return () => this.listeners.delete(listener)
  }

  updateDocumentLanguage () {
    if (typeof document !== 'undefined') {
      document.documentElement.lang = this.locale === 'zh' ? 'zh-CN' : this.locale
    }
  }
}
